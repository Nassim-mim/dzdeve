  function getPage() {
    return document.body.getAttribute("data-page") || "index";
  }

  function getLang() {
    const stored = localStorage.getItem("dzdeve-lang");
    return stored === "ar" ? "ar" : "fr";
  }

  function setLanguage(lang) {
    const page = getPage();
    const pageDict = translations[page];
    if (!pageDict || !pageDict[lang]) {
      return;
    }

    const dict = pageDict[lang];
    const html = document.documentElement;

    html.setAttribute("lang", lang);
    html.setAttribute("dir", lang === "ar" ? "rtl" : "ltr");
    document.body.classList.toggle("lang-ar", lang === "ar");

    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      if (dict[key]) {
        el.textContent = dict[key];
      }
    });

    document.querySelectorAll("[data-i18n-html]").forEach((el) => {
      const key = el.getAttribute("data-i18n-html");
      if (dict[key]) {
        el.innerHTML = dict[key];
      }
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      const key = el.getAttribute("data-i18n-placeholder");
      if (dict[key]) {
        el.setAttribute("placeholder", dict[key]);
      }
    });

    document.querySelectorAll("[data-i18n-alt]").forEach((el) => {
      const key = el.getAttribute("data-i18n-alt");
      if (dict[key]) {
        el.setAttribute("alt", dict[key]);
      }
    });

    const titleEl = document.querySelector("title[data-i18n]");
    if (titleEl && dict[titleEl.getAttribute("data-i18n")]) {
      document.title = dict[titleEl.getAttribute("data-i18n")];
    }

    const descEl = document.querySelector('meta[name="description"][data-i18n]');
    if (descEl && dict[descEl.getAttribute("data-i18n")]) {
      descEl.setAttribute("content", dict[descEl.getAttribute("data-i18n")]);
    }

    document.querySelectorAll(".lang-switch-btn").forEach((btn) => {
      btn.textContent = lang === "fr" ? "AR" : "FR";
      btn.setAttribute(
        "aria-label",
        lang === "fr" ? "Switch to Arabic" : "Passer en français"
      );
    });

    localStorage.setItem("dzdeve-lang", lang);
  }

  function bindSwitches() {
    document.querySelectorAll(".lang-switch-btn").forEach((btn) => {
      btn.addEventListener("click", function () {
        const current = getLang();
        const next = current === "fr" ? "ar" : "fr";
        setLanguage(next);
      });
    });
  }

  function t(key) {
    const page = getPage();
    const lang = getLang();
    const dict = translations[page] && translations[page][lang];
    if (!dict) {
      return key;
    }
    return dict[key] || key;
  }

  window.dzI18n = {
    getLang,
    setLanguage,
    t
  };

  document.addEventListener("DOMContentLoaded", function () {
    bindSwitches();
    setLanguage(getLang());
  });
